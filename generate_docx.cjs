const FONT = 'Times New Roman';
const CODE_FONT = 'Courier New';
const SIZE = 24; // 12pt in half-points
const LINE_SPACING = 276; // 1.15 line spacing
const INDENT = 709; // 1.25 cm in dxa

// Стандартты негізгі абзац
function p(text, options = {}) {
  const isCenter = options.align === 'center';
  const isRight = options.align === 'right';
  const isLeft = options.align === 'left';
  const noIndent = options.noIndent || isCenter || isRight || isLeft;

  return new Paragraph({
    alignment: isCenter
      ? AlignmentType.CENTER
      : isRight
      ? AlignmentType.RIGHT
      : isLeft
      ? AlignmentType.LEFT
      : AlignmentType.JUSTIFIED,
    indent: noIndent ? undefined : { firstLine: INDENT },
    spacing: {
      line: options.line || LINE_SPACING,
      before: options.spaceBefore || 0,
      after: options.spaceAfter !== undefined ? options.spaceAfter : 90,
    },
    children: [
      new TextRun({
        text,
        font: options.font || FONT,
        size: options.size || SIZE,
        bold: options.bold || false,
        italics: options.italics || false,
        color: options.color,
      }),
    ],
  });
}

// Тарау атауы (Ортаға, Қою, Бас әріптермен, нүктесіз)
function h1(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 120, after: 180 },
    children: [
      new TextRun({
        text,
        font: FONT,
        size: SIZE,
        bold: true,
      }),
    ],
  });
}

// Бөлімше атауы (Сол жақтан 1.25см шегініс, Қою, нүктесіз)
function h2(text) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    indent: { firstLine: INDENT },
    spacing: { before: 160, after: 110 },
    children: [
      new TextRun({
        text,
        font: FONT,
        size: SIZE,
        bold: true,
      }),
    ],
  });
}

// Тізім элементі
function bullet(text) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    indent: { left: INDENT, hanging: 240 },
    spacing: { line: LINE_SPACING, before: 25, after: 55 },
    children: [
      new TextRun({
        text: '– ' + text,
        font: FONT,
        size: SIZE,
      }),
    ],
  });
}

// Бағдарламалық код блогы (моноширинді қаріп, жиектелген)
function codeBlock(codeText) {
  const lines = codeText.split('\n');
  const borderGrey = { style: BorderStyle.SINGLE, size: 4, color: 'CBD5E1' };
  const borders = {
    top: borderGrey,
    bottom: borderGrey,
    left: { style: BorderStyle.SINGLE, size: 12, color: '0D9488' },
    right: borderGrey,
  };

  return new Table({
    width: { size: 9300, type: WidthType.DXA },
    rows: [
      new TableRow({
        children: [
          new TableCell({
            borders,
            shading: { fill: 'F8FAFC' },
            margins: { top: 100, bottom: 100, left: 160, right: 120 },
            children: lines.map(
              (line) =>
                new Paragraph({
                  alignment: AlignmentType.LEFT,
                  spacing: { before: 0, after: 20, line: 220 },
                  children: [
                    new TextRun({
                      text: line.length ? line : ' ',
                      font: CODE_FONT,
                      size: 18, // 9pt monospace
                      color: '0F172A',
                    }),
                  ],
                })
            ),
          }),
        ],
      }),
    ],
  });
}

// Мазмұны кестесінің жолы (шекарасыз)
function tocRow(title, pageNum, isBold = false) {
  const borderNone = { style: BorderStyle.NONE, size: 0, color: 'FFFFFF' };
  const borders = {
    top: borderNone,
    bottom: borderNone,
    left: borderNone,
    right: borderNone,
  };

  return new TableRow({
    children: [
      new TableCell({
        borders,
        width: { size: 8300, type: WidthType.DXA },
        children: [
          new Paragraph({
            spacing: { before: 50, after: 50, line: 260 },
            children: [
              new TextRun({
                text: title,
                font: FONT,
                size: SIZE,
                bold: isBold,
              }),
            ],
          }),
        ],
      }),
      new TableCell({
        borders,
        width: { size: 1000, type: WidthType.DXA },
        children: [
          new Paragraph({
            alignment: AlignmentType.RIGHT,
            spacing: { before: 50, after: 50, line: 260 },
            children: [
              new TextRun({
                text: String(pageNum),
                font: FONT,
                size: SIZE,
                bold: isBold,
              }),
            ],
          }),
        ],
      }),
    ],
  });
}

// Кесте ұяшығы
function tableCell(text, isHeader = false, widthDxa = 3000) {
  return new TableCell({
    width: { size: widthDxa, type: WidthType.DXA },
    shading: isHeader ? { fill: 'F1F5F9' } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [
      new Paragraph({
        alignment: isHeader ? AlignmentType.CENTER : AlignmentType.LEFT,
        spacing: { before: 20, after: 20, line: 240 },
        children: [
          new TextRun({
            text,
            font: FONT,
            size: 21, // 10.5pt кесте ішінде ықшам әрі анық
            bold: isHeader,
          }),
        ],
      }),
    ],
  });
}

// Нақты PNG суретті енгізу көмекшісі (ImageRun)
function embeddedFigure(imageRelPath, widthPx, heightPx, figureNum, caption) {
  const fullPath = path.resolve(__dirname, imageRelPath);
  const imgBuffer = fs.readFileSync(fullPath);

  return [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 120, after: 80 },
      children: [
        new ImageRun({
          data: imgBuffer,
          transformation: {
            width: widthPx,
            height: heightPx,
          },
          type: 'png',
        }),
      ],
    }),
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { before: 40, after: 140 },
      children: [
        new TextRun({
          text: `${figureNum}-сурет – ${caption}`,
          font: FONT,
          size: 22, // 11pt
          bold: true,
        }),
      ],
    }),
  ];
}

function pageBreak() {
  return new Paragraph({ children: [new PageBreak()] });
}

